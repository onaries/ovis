import { randomUUID } from "node:crypto";
import { chmodSync, closeSync, linkSync, lstatSync, mkdirSync, openSync, readFileSync, readSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

/**
 * Keeps only what usage reads from the payload Claude Code hands its status line: the five-hour and
 * weekly windows, and the account of the CLI that drew it (from its config, not whichever account
 * is signed in at read time). The rest of the payload (cwd, cost, session, transcript path) is
 * never written. The file starts with the installer's mark (MARK in server/statusline-install.ts),
 * and one at that path without it is not this capture's, so it is never replaced.
 */
const GENERATED = "Generated by the herdr web UI's status-line installer (server/statusline-install.ts); do not edit.";
const MARK = `{"generatedBy":${JSON.stringify(GENERATED)},`;
const home = homedir();
const dir = join(home, ".herdr");
const path = join(dir, "statusline-last.json");
const temp = join(dir, `.statusline-last.json.${process.pid}.${randomUUID()}.tmp`);
let wrote = false;
/** Whether `file` is a regular file (not a link, even to nothing) that starts with `mark`. */
function startsWith(file: string, mark: string): boolean {
  if (!lstatSync(file, { throwIfNoEntry: false })?.isFile()) return false;
  const fd = openSync(file, "r");
  try {
    const start = Buffer.alloc(Buffer.byteLength(mark));
    let read = 0;
    for (let got = 1; got > 0 && read < start.length; read += got) got = readSync(fd, start, read, start.length - read, read);
    return start.subarray(0, read).toString("utf8") === mark;
  } finally {
    closeSync(fd);
  }
}
const record = (value: unknown): Record<string, unknown> => (typeof value === "object" && value !== null && !Array.isArray(value) ? value as Record<string, unknown> : {});
const number = (value: unknown): number | undefined => (typeof value === "number" && Number.isFinite(value) ? value : undefined);
function window(value: unknown): { used_percentage: number; resets_at?: number } | undefined {
  const found = record(value);
  const used = number(found["used_percentage"]);
  return used === undefined ? undefined : { used_percentage: used, resets_at: number(found["resets_at"]) };
}
/** Claude's payload is a few kilobytes; one past this is not read whole, and the last reading stays. */
const MAX_PAYLOAD_BYTES = 256 * 1024;
async function payload(): Promise<string | null> {
  const chunks: Uint8Array[] = [];
  let size = 0;
  for await (const chunk of Bun.stdin.stream()) {
    size += chunk.byteLength;
    if (size > MAX_PAYLOAD_BYTES) return null;
    chunks.push(chunk);
  }
  return Buffer.concat(chunks).toString("utf8");
}
try {
  const text = await payload();
  if (text === null) process.exit(0);
  const limits = record(record(JSON.parse(text))["rate_limits"]);
  const fiveHour = window(limits["five_hour"]);
  const sevenDay = window(limits["seven_day"]);
  // a render before Claude's first answer names no limits; the last reading stays
  if (fiveHour === undefined && sevenDay === undefined) process.exit(0);
  const configDir = process.env["CLAUDE_CONFIG_DIR"];
  let account: { id: string; label: string | null } | null = null;
  try {
    const config = JSON.parse(readFileSync(configDir ? join(configDir, ".claude.json") : join(home, ".claude.json"), "utf8"));
    const oauth = config.oauthAccount;
    if (typeof oauth?.accountUuid === "string" && oauth.accountUuid.trim()) {
      account = { id: oauth.accountUuid.trim(), label: typeof oauth.emailAddress === "string" ? oauth.emailAddress : null };
    }
  } catch { /* An unknown account is never attributed to a sign-in by the reader. */ }
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  chmodSync(dir, 0o700);
  const absent = lstatSync(path, { throwIfNoEntry: false }) === undefined;
  // anything there but a payload this capture wrote is someone else's, and stays
  if (absent || startsWith(path, MARK)) {
    // the name is this run's own (its pid and a random uuid), so whatever is there is its to delete
    wrote = true;
    writeFileSync(temp, `${MARK}${JSON.stringify({ rate_limits: { five_hour: fiveHour, seven_day: sevenDay }, _herdr: { account } }).slice(1)}`, { mode: 0o600, flag: "wx" });
    // turned off while this ran (the switch deletes this helper, or the file is no longer the
    // installer's): a reading now would outlive the removal
    if (startsWith(import.meta.path, `// ${GENERATED}\n`)) {
      // nothing there: a link creates it only while still nothing is, never over a file made meanwhile
      if (!absent) renameSync(temp, path);
      else {
        try { linkSync(temp, path); } catch (error) {
          // a file system without hard links: a rename, while there is still nothing there
          if ((error as { code?: string }).code === "EEXIST" || lstatSync(path, { throwIfNoEntry: false }) !== undefined) throw error;
          renameSync(temp, path);
        }
      }
    }
  }
} catch { /* Capture must not prevent the original status line from rendering. */ }
finally { if (wrote) rmSync(temp, { force: true }); }
