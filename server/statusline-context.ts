import { createHash as contextHash, randomUUID as contextUUID } from "node:crypto";
import * as contextFs from "node:fs";
import { dirname as contextDirname, join as contextJoin } from "node:path";

/** Also embedded in the installed capture, so capture and removal use the same protocol. */
export const CONTEXT_GENERATED = "Generated by the herdr web UI's status-line installer (server/statusline-install.ts); do not edit.";
export const CONTEXT_MARK = `{"generatedBy":${JSON.stringify(CONTEXT_GENERATED)},`;
export const CONTEXT_STALE_MS = 6 * 60 * 60_000;
export const contextProfile = (configDir: string): string => contextHash("sha256").update(contextFs.realpathSync(configDir)).digest("hex");
export const contextFilename = (profile: string, session: string): string => `${profile.slice(0, 16)}-${session}.json`;

export function contextDirectorySafe(directory: string): boolean {
  const stat = contextFs.lstatSync(directory, { throwIfNoEntry: false });
  return process.getuid !== undefined && stat !== undefined && stat.isDirectory()
    && stat.uid === process.getuid() && (stat.mode & 0o077) === 0;
}

/** No following the final link, no FIFO wait, and no unbounded read after fstat. */
export function readContextFile(path: string, profile: string) {
  const fd = contextFs.openSync(path, contextFs.constants.O_RDONLY | contextFs.constants.O_NOFOLLOW | contextFs.constants.O_NONBLOCK);
  try {
    const stat = contextFs.fstatSync(fd);
    if (process.getuid === undefined || !stat.isFile() || stat.uid !== process.getuid() || stat.size > 4096) return null;
    const buffer = Buffer.alloc(4097);
    let size = 0;
    for (let got = 1; got > 0 && size < buffer.length; size += got) got = contextFs.readSync(fd, buffer, size, buffer.length - size, size);
    if (size > 4096) return null;
    const text = buffer.subarray(0, size).toString("utf8");
    if (!text.startsWith(CONTEXT_MARK)) return null;
    const body: unknown = JSON.parse(text);
    if (typeof body !== "object" || body === null || !("_herdr" in body)
      || typeof body._herdr !== "object" || body._herdr === null
      || !("profile" in body._herdr) || body._herdr.profile !== profile) return null;
    return { body, mtimeMs: stat.mtimeMs };
  } finally {
    contextFs.closeSync(fd);
  }
}

/**
 * Move first, inspect the moved inode, then unlink only our capture. A foreign entry is
 * linked back without overwriting a newcomer; if that fails it stays in a visible recovery file.
 * Pathname-only POSIX APIs cannot pin the parent directory against a concurrent same-user rename.
 */
export function removeContextFile(path: string, profile: string, olderThan = Infinity): boolean {
  const directory = contextDirname(path);
  if (!contextDirectorySafe(directory)) return false;
  const id = contextUUID();
  const quarantine = contextJoin(directory, `.statusline-context-${id}.quarantine`);
  try {
    contextFs.renameSync(path, quarantine);
  } catch (error) {
    if (error !== null && typeof error === "object" && "code" in error && error.code === "ENOENT") return true;
    return false;
  }
  let owned = false;
  try {
    const capture = readContextFile(quarantine, profile);
    owned = capture !== null && capture.mtimeMs < olderThan;
  } catch { /* Invalid, linked or unreadable entries belong to the user, not this installation. */ }
  if (owned) {
    contextFs.unlinkSync(quarantine);
    return true;
  }
  try {
    contextFs.linkSync(quarantine, path);
  } catch {
    // Includes EEXIST, and directories (which cannot be hard linked). Never replace the original.
    for (let attempt = 0; attempt < 4; attempt++) {
      const recovery = contextJoin(directory, `statusline-context-recovery-${attempt === 0 ? id : contextUUID()}`);
      try {
        contextFs.linkSync(quarantine, recovery);
      } catch { continue; /* Keep quarantine if no recovery name can be published. */ }
      contextFs.unlinkSync(quarantine);
      break;
    }
    return false;
  }
  contextFs.unlinkSync(quarantine);
  return false;
}

/** Best-effort, bounded work only when a new session publishes, not on every status-line render. */
export function pruneContextFiles(directory: string, profile: string, now: number): void {
  if (!contextDirectorySafe(directory)) return;
  const entries = contextFs.opendirSync(directory);
  const candidates: { path: string; mtimeMs: number }[] = [];
  const pattern = new RegExp(`^${profile.slice(0, 16)}-[a-zA-Z0-9-]{1,128}\\.json$`);
  try {
    for (let entry = entries.readSync(); entry !== null; entry = entries.readSync()) {
      if (!pattern.test(entry.name)) continue;
      const path = contextJoin(directory, entry.name);
      try {
        const { mtimeMs } = contextFs.lstatSync(path);
        if (mtimeMs < now - CONTEXT_STALE_MS) candidates.push({ path, mtimeMs });
      } catch { /* Another render/removal may have moved it. */ }
    }
  } finally {
    entries.closeSync();
  }
  // Inspect at most 128 own captures, oldest first; foreign names cannot consume the budget.
  for (const { path } of candidates.sort((a, b) => a.mtimeMs - b.mtimeMs).slice(0, 128)) {
    try { removeContextFile(path, profile, now - CONTEXT_STALE_MS); }
    catch { /* Another render/removal may have moved it. */ }
  }
}

/** Exclusive temp creation and hard-link publication never overwrite a target. */
export function publishContext(directory: string, profile: string, capture: { session_id: string; model: string; window: number }): void {
  if (!contextDirectorySafe(directory)) return;
  const pending = contextJoin(directory, `.${capture.session_id}.${contextUUID()}.tmp`);
  let created = false;
  try {
    const fd = contextFs.openSync(pending, "wx", 0o600);
    created = true;
    try {
      contextFs.writeFileSync(fd, `${CONTEXT_MARK}${JSON.stringify({ ...capture, _herdr: { profile } }).slice(1)}`);
    } finally {
      contextFs.closeSync(fd);
    }
    const target = contextJoin(directory, contextFilename(profile, capture.session_id));
    let fresh = true;
    try {
      contextFs.linkSync(pending, target);
    } catch (error) {
      if (error === null || typeof error !== "object" || !("code" in error) || error.code !== "EEXIST") throw error;
      fresh = false;
      if (!removeContextFile(target, profile)) return;
      contextFs.linkSync(pending, target); // EEXIST means a newcomer won: leave it alone.
    }
    if (fresh) pruneContextFiles(directory, profile, Date.now());
  } catch { /* Context is optional; never interrupt quota capture or the original status line. */ }
  finally {
    if (created) contextFs.unlinkSync(pending);
  }
}
