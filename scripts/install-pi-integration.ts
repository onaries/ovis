import { join } from "node:path";
import { piAgentDir } from "../integrations/pi-ask.ts";
import { buildIntegration, installExtensionFile, type InstallGjcIntegrationResult } from "./install-gjc-integration.ts";

export const PI_INTEGRATION_OWNERSHIP_BANNER = "// Generated by herdr-web-ui pi integration installer; do not edit.";

export interface InstallPiIntegrationOptions {
  /** pi's agent directory; by default the one pi itself uses (PI_CODING_AGENT_DIR, else ~/.pi/agent). */
  agentDir?: string;
  remove?: boolean;
  build?: () => Promise<string>;
}

/** Install or remove only herdr-web-ui.js in pi's own extensions directory, which pi loads by itself. */
export default async function installPiIntegration(options: InstallPiIntegrationOptions = {}): Promise<InstallGjcIntegrationResult> {
  return installExtensionFile(join(options.agentDir ?? piAgentDir(), "extensions", "herdr-web-ui.js"), PI_INTEGRATION_OWNERSHIP_BANNER, {
    remove: options.remove,
    build: options.build ?? (() => buildIntegration("pi-ask", "node")),
  });
}

function parseArguments(args: string[]): InstallPiIntegrationOptions {
  const options: InstallPiIntegrationOptions = {};
  for (const arg of args) {
    if (arg === "--remove") options.remove = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return options;
}

if (import.meta.main) {
  try {
    const result = await installPiIntegration(parseArguments(Bun.argv.slice(2)));
    if (result.action === "installed") {
      console.log(`Installed pi integration: ${result.path}`);
      console.log("Restart existing pi sessions to load the integration.");
    } else {
      console.log(`Removed pi integration: ${result.path}`);
      console.log("Restart existing pi sessions for the change to take effect.");
    }
  } catch (error) {
    console.error(`pi integration installer failed: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}
